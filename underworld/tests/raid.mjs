/* Raiding a rival warehouse (Session 4B: §9, §39 scenarios 14-16 and 39, §45.27).
   - Each gang has a physical warehouse compound with its own gate (shut to you), cameras and guards, and a saved,
     authoritative stock. The rooms inside are drawn from that stock; going in and out never changes it.
   - Taking stock is a transfer like any other (from inside, or into a car in their loading bay): exact, atomic, and
     only out of their shelves, never into them. Take half, leave, unload at your own warehouse, come back: the
     other half is still there. A reload keeps both sides exactly, and nothing can be taken twice.
   - A raid starts when they notice you, runs on a saved real-time clock: guards only for about 4.5 minutes, then
     reinforcements, a stronger response from 7 minutes, and from 10 minutes an evacuation van that loads what is
     left (off their shelves, onto the van) and drives it to their HQ. Stop or steal the van and the load is lost to
     them or yours. Walk away and the raid winds down with the stock as it stands.
   - Only an actual delivery restocks them (a shipment that arrives), and not while a raid is on. */
